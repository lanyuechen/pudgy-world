/**
 * Survival combat HUD — top-right kill count with skull icon.
 */
export function createCombatHud() {
  let el = document.getElementById('combat-hud');
  if (!el) {
    el = document.createElement('div');
    el.id = 'combat-hud';
    el.innerHTML =
      `<div class="combat-hud-inner" aria-label="击杀数">` +
      SKULL_ICON +
      `<span class="combat-hud-score">0</span>` +
      `</div>`;
    document.getElementById('app')?.appendChild(el);
  }

  const scoreEl = el.querySelector('.combat-hud-score');
  let kills = 0;
  let waveTotal = 0;

  function renderScore() {
    if (scoreEl) scoreEl.textContent = String(kills);
  }

  function setVisible(visible) {
    el.hidden = !visible;
  }

  function setWaveTotal(total) {
    waveTotal = Math.max(0, total | 0);
  }

  function addKill() {
    kills += 1;
    renderScore();
  }

  function resetWave(total) {
    setWaveTotal(total);
  }

  function reset(total = 0) {
    kills = 0;
    setWaveTotal(total);
    renderScore();
  }

  function update() {}

  function dispose() {
    el.remove();
  }

  return {
    setVisible,
    setWaveTotal,
    addKill,
    resetWave,
    reset,
    update,
    dispose,
  };
}
